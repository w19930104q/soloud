#ifndef SOLOUD_CHANNELMIXER_H
#define SOLOUD_CHANNELMIXER_H

#include "soloud.h"

namespace SoLoud
{
	class ChannelMixer;

	// Composable channel-mapping playback source.
	//
	// Wraps any other AudioSource and converts the wrapped source's channel
	// layout into the mixer's own output layout through an explicit, fully
	// user-editable mapping matrix, while optionally running the stream at a
	// configured output sample rate. The output layout (channel count) and the
	// output sample rate are applied by a single configure() call, i.e. one
	// atomic configuration transaction.
	//
	// Matrix convention: mMapping[dst][src] is the gain of source channel
	// 'src' into output channel 'dst'.
	//
	// The default matrix generated by configure() follows the channel order
	// documented in soloud.h (1=mono, 2=stereo, 4=quad, 6=5.1, 8=7.1):
	//   - identical speakers pass through at gain 1.0;
	//   - a stereo pair (L,R) folded onto one speaker uses the equal-power
	//     gain 1/sqrt(2), so a stereo (0.2,-0.4) downmix is -0.141421;
	//   - the LFE channel only ever feeds an LFE output and is therefore
	//     never mixed into the left/right (or any other full-range) speaker;
	//   - the remaining coefficients reproduce the engine's existing public
	//     panAndExpand() down/up-mix coefficients.
	class ChannelMixerInstance : public AudioSourceInstance
	{
	public:
		ChannelMixerInstance(ChannelMixer *aParent);
		virtual ~ChannelMixerInstance();
		virtual unsigned int getAudio(float *aBuffer, unsigned int aSamplesToRead, unsigned int aBufferSize);
		virtual bool hasEnded();
		virtual result rewind();

	private:
		// Pull one block of inner-source data and apply the mapping matrix;
		// the cached planar result is consumed and linearly resampled by
		// getAudio(). Leftover playhead state stays between calls.
		void refillBlock();

		ChannelMixer *mParent;
		// Wrapped source's playback instance, owned by this object
		AudioSourceInstance *mInner;
		// Planar block of mapped (pre-resample) output frames
		float *mMapped;
		// Planar block pulled from the inner source
		float *mInnerBlock;
		// Last frame of the previous mapped block, per output channel, so the
		// linear resampler can interpolate across block boundaries
		float mLastFrame[MAX_CHANNELS];
		// Fixed-point (20 fractional bits) continuous resample playhead
		unsigned int mSrcOffset;
		// Number of valid frames currently in mMapped
		unsigned int mMappedFrames;
		// Number of inner blocks pulled so far (drives first-frame seeding)
		unsigned int mBlocksSeen;
	};

	class ChannelMixer : public AudioSource
	{
	public:
		// Channel indices in the public 5.1 / 7.1 layouts (see soloud.h).
		// LFE must never contribute to full-range speakers.
		enum CHANNEL
		{
			MONO = 0,
			FRONT_LEFT = 0,
			FRONT_RIGHT = 1,
			FRONT_CENTER = 2,
			LFE = 3,
			BACK_LEFT = 4,
			BACK_RIGHT = 5,
			SIDE_LEFT = 6,
			SIDE_RIGHT = 7
		};

		ChannelMixer();
		virtual ~ChannelMixer();

		// Wrap a source and apply a configuration transaction in one call.
		// Either aSource is non-NULL, or setSource() has been called earlier.
		// Validates every parameter before touching the object, so a failed
		// call leaves the current configuration (and any playing instances)
		// untouched. aSamplerate 0 means "keep the wrapped source's rate".
		result configure(AudioSource *aSource, unsigned int aChannels, float aSamplerate = 0.0f);

		// Replace only the wrapped source; channel layout, matrix and output
		// sample rate stay in effect. The new source must produce the same
		// number of channels as the matrix expects.
		result setSource(AudioSource *aSource);

		// Overwrite one matrix coefficient (gain of source channel aSrcChannel
		// into output channel aDstChannel).
		result setMapping(unsigned int aDstChannel, unsigned int aSrcChannel, float aGain);
		// Read one matrix coefficient.
		float getMapping(unsigned int aDstChannel, unsigned int aSrcChannel) const;
		// Regenerate the default mapping matrix for the current layouts.
		result resetMapping();

		// Accessors for the configuration transaction.
		unsigned int getSourceChannels() const;
		float getOutputSamplerate() const;

		virtual AudioSourceInstance *createInstance();

		// Wrapped source. Not owned: caller keeps the object alive, as with
		// every other SoLoud source reference.
		AudioSource *mSource;
		// Mapping matrix, mMapping[dst][src]
		float mMapping[MAX_CHANNELS][MAX_CHANNELS];
		// Output sample rate of this source; 0 follows the inner source
		float mOutputSamplerate;
	};
};

#endif
