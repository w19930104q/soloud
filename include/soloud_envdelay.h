#ifndef SOLOUD_ENVDELAY_H
#define SOLOUD_ENVDELAY_H

#include "soloud.h"

namespace SoLoud
{
	class EnvDelay;

	// Environment delay instance. Wraps another audio source instance and
	// keeps feeding its delay line after the wrapped source has ended, so
	// the first reflection, the repeated feedback taps and the tail after
	// the source material finishes are all generated by the same continuous
	// stream and are never cut short.
	class EnvDelayInstance : public AudioSourceInstance
	{
	public:
		EnvDelayInstance(EnvDelay *aParent);
		~EnvDelayInstance();

		virtual unsigned int getAudio(float *aBuffer, unsigned int aSamplesToRead, unsigned int aBufferSize);
		virtual bool hasEnded();
		virtual result rewind();

	private:
		// Wrapped ("dry") source instance
		AudioSourceInstance *mSource;
		// Delay line, one planar buffer per channel, mDelayFrames samples each
		float *mDelayBuffer;
		// Delay length in source frames
		unsigned int mDelayFrames;
		// Feedback gain (0..1), applied when a sample is fed back into the line
		float mFeedback;
		// Wet (echo) mix level (0..1); dry level is 1 - wet
		float mWet;
		// Circular write offset in the delay line
		unsigned int mOffset;
		// Scratch for pulling dry material from the wrapped source
		float *mDryBuffer;
		// Set once the wrapped source has run out of data
		bool mSourceEnded;
		// Set once the feedback tail has decayed below the tail threshold
		bool mTailEnded;
	};

	// Environment delay audio source. Wraps any other audio source (Wav,
	// WavStream, etc.) with a feedback delay line. Unlike filters, the
	// source stays alive until the delay tail has also decayed to silence,
	// so cutting the camera / ending the material does not truncate the
	// echo tail.
	class EnvDelay : public AudioSource
	{
	public:
		EnvDelay();
		virtual ~EnvDelay();

		// Configure the delay. aSource is the dry material to wrap (not
		// owned by EnvDelay). aDelayFrames is the delay length in source
		// frames, aFeedback is the feedback gain [0..1), aWet is the echo
		// mix level [0..1]. Invalid parameters are rejected at this
		// configuration stage; members are only written after all checks
		// pass, so a failed call leaves any previous configuration intact.
		result setParams(AudioSource &aSource, unsigned int aDelayFrames, float aFeedback = 0.5f, float aWet = 0.5f);

		virtual AudioSourceInstance *createInstance();

		// Wrapped dry source (not owned)
		AudioSource *mSource;
		// Delay length in source frames
		unsigned int mDelayFrames;
		// Feedback gain
		float mFeedback;
		// Wet (echo) mix level
		float mWet;
	};
};

#endif
